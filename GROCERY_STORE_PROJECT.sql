-- 2. PRODUCT PERFORMANCE
-- HOW MANY PRODUCTS EXIST IN EACH CATEGORY
SELECT CAT_NAME, COUNT(*) AS TOTLA_PRODUCTS
FROM PRODUCTS P
JOIN CATEGORIES C ON P.CAT_ID = C.CAT_ID
GROUP BY CAT_NAME;

-- WHAT IS TH EAVERAGE PRICE OF PRODUCT BY THE CATEGORIES
SELECT CAT_NAME, AVG(PRICE) AS AVG_PRICE
FROM PRODUCTS P
JOIN CATEGORIES C ON P.CAT_ID = C.CAT_ID
GROUP BY CAT_NAME;

-- WHICH PRODUCT HAS THE HIGEST TOTAL SALES VOLUME (BY QUANTITY)
SELECT P.PROD_NAME, SUM(OD.QUANTITY) AS TOTAL_QTY
FROM ORDER_DETAILS OD
JOIN PRODUCTS P ON OD.PROD_ID = P.PROD_ID
GROUP BY P.PROD_NAME
ORDER BY TOTAL_QTY DESC;

-- WHAT IS THE TOTAL REVENUE GENERATED BY EACH PRODUCT
SELECT P.PROD_NAME, SUM(OD.TOTAL_PRICE) AS REVENUE
FROM ORDER_DETAILS OD
JOIN PRODUCTS P ON OD.PROD_ID = P.PROD_ID
GROUP BY P.PROD_NAME
ORDER BY REVENUE DESC;

-- HOW DO PRODUCT SALES VARY BY CATEGORY AND SUPPLIERS
SELECT C.CAT_NAME, S.SUP_NAME, SUM(OD.TOTAL_PRICE) AS TOTAL_REVENUE, SUM(OD.QUANTITY) AS TOTAL_QUANTITY
FROM ORDER_DETAILS OD 
JOIN PRODUCTS P ON OD.PROD_ID = P.PROD_ID
JOIN CATEGORIES C ON P.CAT_ID = C.CAT_ID
JOIN SUPPLIER S ON P.SUP_ID
GROUP BY C.CAT_NAME, S.SUP_NAME
ORDER BY C.CAT_NAME, TOTAL_REVENUE DESC;

